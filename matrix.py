import numpy as np
from numpy.linalg import det
print("=== Работа с матрицами ===")
# Вводим размеры с клавиатуры
n = int(input("Введите количество строк N: "))
m = int(input("Введите количество столбцов M: "))
# Создаем матрицу со случайными числами от 1 до 9
mt = np.random.randint(1, 10, size=(n, m))
print("\n--- Исходная матрица ---")
print(mt)
# Делаем транспонированную матрицу
mt_t = mt.T
print("\n--- Транспонированная матрица ---")
print(mt_t)
# Проверяем, квадратная ли матрица, чтобы посчитать определитель
if n == m:
    # Считаем определители просто через det()
    det_original = round(det(mt), 4)
    det_transposed = round(det(mt_t), 4)
    print("\nОпределитель исходной матрицы:", det_original)
    print("Определитель транспонированной матрицы:", det_transposed)
    # Сравниаем их
    if det_original == det_transposed:
        print("Результат сравнения: Определители равны")
    else:
        print("Результат сравнения: Определители не равны")
else:
    print("\nМатрицы не квадратные, определитель посчитать нельзя!")
